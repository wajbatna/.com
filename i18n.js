export function getLang() {
  try {
    const l = localStorage.getItem("wajba_lang");
    return l === "fr" ? "fr" : "ar";
  } catch (e) {
    return "ar";
  }
}
export function setLang(lang) {
  try {
    localStorage.setItem("wajba_lang", lang);
  } catch (e) {
    /* التخزين غير متاح (وضع خاص) — نتجاهل */
  }
}
